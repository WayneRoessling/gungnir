//! A staged store drawn by view on the desktop (GAP-227,
//! `docs/design/DN-36-staged-terrain-and-map-tiles.md` §5.1 and §5.3): the viewport asks
//! for the tiles its view wants, the desktop places them off the render thread, the
//! picture draws them as one surface under the frame's budget, and where ground is missing
//! the map and PN-09 say so (§8.1 row g, a draft and not a gate).

use std::path::PathBuf;

use gungnir_app::picture::{render_projection, PictureCache, Sources};
use gungnir_app::state::AppState;
use gungnir_app::terrain::TerrainStatus;
use gungnir_app::{terrain_tiles, update};
use gungnir_config::{ConfigBaseline, TerrainConfig};
use gungnir_data::geospatial::{GridCrs, HeightGrid};
use gungnir_data::terrain_store::{stage, ManifestSource, StageOptions, TileKey};
use gungnir_ui::harness::{DrawnFrame, RenderProbe};
use gungnir_viewport3d::interaction::TopDownView;
use gungnir_viewport3d::layers::TERRAIN_VERTEX_BUDGET;

/// A 64 by 64 store of 10 m cells in the local frame, 16-cell tiles: level 0 is four by
/// four tiles over 640 m by 640 m.
fn desktop(name: &str, tamper: Option<TileKey>) -> (AppState, PathBuf) {
    desktop_in(name, tamper, Frame::Local)
}

/// The frame the test store is staged in.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Frame {
    Local,
    /// UTM zone 33N, ellipsoidal heights, its south-west corner at 500 000 E, 6 000 000 N.
    #[cfg_attr(not(feature = "crs"), allow(dead_code))]
    Utm,
}

fn desktop_in(name: &str, tamper: Option<TileKey>, frame: Frame) -> (AppState, PathBuf) {
    let dir = std::env::temp_dir().join(format!("gungnir-app-tiles-{name}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    let mut heights = Vec::new();
    for r in 0..64_u8 {
        for c in 0..64_u8 {
            heights.push(200.0 + f32::from(c) - f32::from(r) * 0.5);
        }
    }
    let grid = HeightGrid {
        columns: 64,
        rows: 64,
        origin: match frame {
            Frame::Local => [0.0, 0.0],
            Frame::Utm => [500_000.0, 6_000_000.0],
        },
        cell_size: [10.0, 10.0],
        nodata: None,
        crs: match frame {
            Frame::Local => GridCrs::Unstated,
            Frame::Utm => GridCrs::Projected { epsg: Some(32633) },
        },
        vertical: None,
        heights,
    };
    let (declared, vertical) = match frame {
        Frame::Local => ("local-enu", None),
        Frame::Utm => ("epsg:32633", Some("ellipsoidal")),
    };
    let store = dir.join("store");
    let (_, digest) = stage(
        &grid,
        &store,
        &StageOptions {
            source: ManifestSource {
                url: "synthetic".into(),
                retrieved: "2026-10-30".into(),
                licence: "none: generated by this test".into(),
            },
            staged_by: "gungnir-app tests".into(),
            frame: declared.into(),
            vertical: vertical.map(str::to_string),
            nad83_realisation: None,
            tile_cells: 16,
            apron_cells: 1,
            levels: None,
        },
    )
    .expect("staged");
    if let Some(key) = tamper {
        let path = store.join(key.relative_path());
        let mut bytes = std::fs::read(&path).expect("tile");
        bytes[0] ^= 0xff;
        std::fs::write(&path, bytes).expect("tampered");
    }
    let config = ConfigBaseline {
        data_dir: dir.join("data").to_string_lossy().into_owned(),
        // The fixture's own south-west corner, 54.148 104 104 N 15 E (`tests/terrain.rs`).
        origin: Some([54.148_104_104_f64.to_radians(), 15.0_f64.to_radians(), 0.0]),
        terrain: Some(TerrainConfig {
            path: None,
            store: Some(store.to_string_lossy().into_owned()),
            manifest_sha256: Some(digest),
            frame: declared.into(),
            vertical: None,
            nad83_realisation: None,
            vertical_sigma_m: None,
        }),
        geoid_grid_dir: Some(dir.join("no-grid-here").to_string_lossy().into_owned()),
        ..ConfigBaseline::default()
    };
    gungnir_config::validate(&config).expect("valid");
    (AppState::with_config(config).expect("starts"), dir)
}

/// The projection drawn once from this state's picture, 800 by 600 points.
fn draw(state: &mut AppState, picture: &mut PictureCache) -> DrawnFrame {
    picture.sync(state);
    let probe = RenderProbe::with_size(800.0, 600.0);
    let (_, frame) = probe.draw(|ui| {
        let (sources, viewport) = Sources::split(state);
        render_projection(ui, picture, &sources, viewport);
    });
    frame
}

/// Tick and draw until `done` holds; a deadlock guard, as `tests/terrain.rs`'s `settle`.
fn until(
    state: &mut AppState,
    picture: &mut PictureCache,
    what: &str,
    done: impl Fn(&AppState) -> bool,
) -> DrawnFrame {
    for _ in 0..3_000 {
        update::tick(state);
        let frame = draw(state, picture);
        if done(state) {
            return frame;
        }
        std::thread::sleep(std::time::Duration::from_millis(10));
    }
    panic!(
        "{what} never happened: {:?}; {:?}",
        state.terrain,
        terrain_tiles::line(state)
    );
}

fn settled(state: &AppState) -> bool {
    let wanted = state.viewport.terrain_tiles.wanted();
    !wanted.is_empty()
        && state.terrain_tiles.pending() == 0
        && wanted.iter().all(|w| {
            state
                .viewport
                .terrain_tiles
                .drawn()
                .iter()
                .any(|d| d.key == w.key)
                || state.terrain_tiles.refused().contains_key(&w.key)
        })
}

#[test]
fn a_store_is_drawn_by_view_under_the_budget() {
    let (mut state, dir) = desktop("drawn", None);
    let mut picture = PictureCache::default();
    // Inside the store: 400 m by 300 m of it in view, 20 points to a cell.
    state.viewport.view = TopDownView {
        center_e: 320.0,
        center_n: 320.0,
        meters_per_px: 0.5,
    };
    let frame = until(&mut state, &mut picture, "the wanted tiles drawn", settled);
    assert!(matches!(state.terrain, TerrainStatus::StoreVerified { .. }));
    let surface = state.viewport.terrain_surface().expect("a ground surface");
    assert!(surface.revision & (1 << 63) != 0, "a joined surface");
    assert!(surface.positions.len() <= TERRAIN_VERTEX_BUDGET);
    assert!(state
        .viewport
        .terrain_tiles
        .drawn()
        .iter()
        .all(|w| w.key.level == 0 && w.stride == 1));
    assert!(
        !frame.says("no staged terrain"),
        "nothing is missing inside the store: {}",
        frame.joined()
    );
    let line = terrain_tiles::line(&state).expect("a store");
    assert!(line.contains("0 loading, 0 refused"), "{line}");
    assert!(state.terrain.line().contains("drawn by view"));
    assert!(
        state.height_field.is_none(),
        "line of sight is the next increment"
    );

    // Zoomed out past the store's edge: a coarser level, and the map says what is missing.
    state.viewport.view.meters_per_px = 4.0;
    let frame = until(
        &mut state,
        &mut picture,
        "the zoomed-out tiles drawn",
        settled,
    );
    assert!(
        frame.says("no staged terrain past the store's edge"),
        "{}",
        frame.joined()
    );
    let line = terrain_tiles::line(&state).expect("a store");
    assert!(
        line.contains("no staged terrain past the store's edge"),
        "{line}"
    );
    let _ = std::fs::remove_dir_all(dir);
}

/// §5.3: a tile refused by its digest is said by name on the map and on PN-09, and the
/// rest of the store is drawn.
#[test]
fn a_refused_tile_is_said_and_the_rest_is_drawn() {
    let tampered = TileKey {
        level: 0,
        column: 1,
        row: 1,
    };
    let (mut state, dir) = desktop("refused", Some(tampered));
    let mut picture = PictureCache::default();
    state.viewport.view = TopDownView {
        center_e: 320.0,
        center_n: 320.0,
        meters_per_px: 0.5,
    };
    let frame = until(&mut state, &mut picture, "the tampered tile refused", |s| {
        settled(s) && s.terrain_tiles.refused().contains_key(&tampered)
    });
    assert!(
        frame.says("tile 0/1_1 refused: digest"),
        "{}",
        frame.joined()
    );
    let line = terrain_tiles::line(&state).expect("a store");
    assert!(line.contains("1 refused"), "{line}");
    assert!(
        state.viewport.terrain_tiles.drawn().len() > 1,
        "the rest of the store is drawn"
    );
    let _ = std::fs::remove_dir_all(dir);
}

/// The same through PROJ: the footprint's corners, which carry no height, and every tile
/// are placed from UTM into local ENU, and the store is drawn around the origin.
#[cfg(feature = "crs")]
#[test]
fn a_utm_store_is_placed_and_drawn() {
    let (mut state, dir) = desktop_in("utm", None, Frame::Utm);
    let mut picture = PictureCache::default();
    state.viewport.view = TopDownView {
        center_e: 320.0,
        center_n: 320.0,
        meters_per_px: 0.5,
    };
    until(&mut state, &mut picture, "the UTM tiles drawn", settled);
    let surface = state.viewport.terrain_surface().expect("a ground surface");
    let e: Vec<f32> = surface.positions.iter().map(|p| p[0]).collect();
    let low = e.iter().copied().fold(f32::INFINITY, f32::min);
    let high = e.iter().copied().fold(f32::NEG_INFINITY, f32::max);
    // Level 0 around the view's centre: within the 640 m store, east of the origin.
    assert!(low > -20.0 && high < 660.0, "{low} to {high}");
    let _ = std::fs::remove_dir_all(dir);
}
