/// 50.25 N, 10.25 E: the middle of the pinned store.
const ORIGIN: [f64; 3] = [
    50.25 * std::f64::consts::PI / 180.0,
    10.25 * std::f64::consts::PI / 180.0,
    0.0,
];

/// Heights over the whole area, so a fill tile and the store agree where they meet.
fn height(lon: f64, lat: f64) -> f32 {
    #[allow(clippy::cast_possible_truncation)]
    let h = (200.0 + 80.0 * (lon * 7.0).sin() + 60.0 * (lat * 5.0).cos()) as f32;
    h
}

/// A grid of `cells` by `cells` over `[west, south]` to `[west + span, south + span]`.
fn grid(west: f64, south: f64, span: f64, cells: u32) -> HeightGrid {
    let cell = span / f64::from(cells);
    let mut heights = Vec::new();
    for r in 0..cells {
        for c in 0..cells {
            let lon = west + (f64::from(c) + 0.5) * cell;
            let lat = south + span - (f64::from(r) + 0.5) * cell;
            heights.push(height(lon, lat));
        }
    }
    HeightGrid {
        columns: cells,
        rows: cells,
        origin: [west, south],
        cell_size: [cell, cell],
        nodata: None,
        crs: GridCrs::Geographic { epsg: Some(4326) },
        vertical: None,
        heights,
    }
}

/// A mirror on the loopback serving `n51e010.tif`, the one-degree tile from 50 to 51 N and
/// 10 to 11 E, and 404 for anything else. Counts the requests it answers.
fn mirror() -> (u16, Arc<AtomicUsize>) {
    let mut bytes = std::io::Cursor::new(Vec::new());
    geotiff::write(&mut bytes, &grid(10.0, 50.0, 1.0, 50)).expect("a fill tile");
    let bytes = bytes.into_inner();
    let listener = std::net::TcpListener::bind("127.0.0.1:0").expect("a loopback port");
    let port = listener.local_addr().expect("bound").port();
    let served = Arc::new(AtomicUsize::new(0));
    let count = Arc::clone(&served);
    std::thread::spawn(move || {
        for stream in listener.incoming() {
            let Ok(mut stream) = stream else { continue };
            let mut request = Vec::new();
            let mut byte = [0_u8; 1];
            while !request.ends_with(b"\r\n\r\n") && stream.read(&mut byte).unwrap_or(0) == 1 {
                request.push(byte[0]);
            }
            count.fetch_add(1, Ordering::SeqCst);
            let found = String::from_utf8_lossy(&request).starts_with("GET /n51e010.tif ");
            let (status, body): (&str, &[u8]) = if found {
                ("200 OK", &bytes)
            } else {
                ("404 Not Found", b"")
            };
            let _ = write!(
                stream,
                "HTTP/1.1 {status}\r\nContent-Length: {}\r\nConnection: close\r\n\r\n",
                body.len()
            );
            let _ = stream.write_all(body);
        }
    });
    (port, served)
}

/// The pinned store: 10.0 to 10.5 E, 50.0 to 50.5 N, 0.01 degree cells in 16-cell tiles.
fn pinned(dir: &Path) -> (PathBuf, String) {
    let store = dir.join("pinned");
    let (_, digest) = stage(
        &grid(10.0, 50.0, 0.5, 50),
        &store,
        &StageOptions {
            source: ManifestSource {
                url: "synthetic".into(),
                retrieved: "2026-10-31".into(),
                licence: "none: generated by this test".into(),
            },
            staged_by: "gungnir-app tests".into(),
            frame: "epsg:4326".into(),
            vertical: Some("ellipsoidal".into()),
            nad83_realisation: None,
            tile_cells: 16,
            apron_cells: 1,
            levels: None,
        },
    )
    .expect("staged");
    (store, digest)
}

fn desktop(dir: &Path, store: &Path, digest: &str, fill_source: Option<String>) -> AppState {
    let config = ConfigBaseline {
        data_dir: dir.join("data").to_string_lossy().into_owned(),
        origin: Some(ORIGIN),
        terrain: Some(TerrainConfig {
            path: None,
            store: Some(store.to_string_lossy().into_owned()),
            manifest_sha256: Some(digest.to_string()),
            fill_source,
            frame: "epsg:4326".into(),
            vertical: None,
            nad83_realisation: None,
            vertical_sigma_m: None,
        }),
        // One radar at the origin reaching 5 km: line of sight's extent is inside the store.
        sensors: vec![SensorConfig {
            id: 1,
            modality: "radar".into(),
            position: [ORIGIN[0], ORIGIN[1], 400.0],
            max_range_m: 5_000.0,
            control_endpoint: None,
            maintenance: Vec::new(),
            detection_model: None,
            azimuth_sector: None,
            elevation_band: None,
        }],
        geoid_grid_dir: Some(dir.join("no-grid-here").to_string_lossy().into_owned()),
        ..ConfigBaseline::default()
    };
    gungnir_config::validate(&config).expect("valid");
    let mut state = AppState::with_config(config).expect("starts");
    // Over the store's east edge, 10.5 E: about 60 km of the view lies east of it.
    state.viewport.view = TopDownView {
        center_e: 17_900.0,
        center_n: 0.0,
        meters_per_px: 75.0,
    };
    state
}

fn draw(state: &mut AppState, picture: &mut PictureCache) -> DrawnFrame {
    picture.sync(state);
    let probe = RenderProbe::with_size(800.0, 600.0);
    let (_, frame) = probe.draw(|ui| {
        let (sources, viewport) = Sources::split(state);
        render_projection(ui, picture, &sources, viewport);
    });
    frame
}

/// Tick and draw until `done`; a deadlock guard, as `tests/terrain.rs`'s `settle`.
fn until(
    state: &mut AppState,
    picture: &mut PictureCache,
    what: &str,
    done: impl Fn(&AppState) -> bool,
) -> DrawnFrame {
    for _ in 0..3_000 {
        update::tick(state);
        let frame = draw(state, picture);
        if done(state) {
            return frame;
        }
        std::thread::sleep(std::time::Duration::from_millis(10));
    }
    panic!(
        "{what} never happened: {:?}; {:?}",
        state.terrain,
        terrain_tiles::line(state)
    );
}

fn scratch(name: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!("gungnir-app-fill-{name}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).expect("scratch");
    dir
}

fn sight_built(state: &AppState) -> bool {
    state.terrain.is_masking() && state.height_field.is_some()
}

/// The field's heights, bit for bit, so `NaN` compares equal to itself.
fn bits(state: &AppState) -> Vec<u32> {
    state
        .height_field
        .as_ref()
        .expect("a field")
        .up_m
        .iter()
        .map(|h| h.to_bits())
        .collect()
}

/// §8.1 rows j, i and k: with a fill source and a mirror, ground past the store's edge is
/// fetched, drawn outlined, said and counted apart; the pinned store is never written; and
/// line of sight is exactly what it is with no fill source at all.
#[test]
fn ground_past_the_edge_is_fetched_marked_and_kept_out_of_line_of_sight() {
    let dir = scratch("fetched");
    let (store, digest) = pinned(&dir);
    let (port, served) = mirror();
    let mut picture = PictureCache::default();

    // With no fill source: the baseline's line of sight.
    let mut alone = desktop(&dir.join("alone"), &store, &digest, None);
    let frame = until(&mut alone, &mut picture, "line of sight, no fill", |s| {
        sight_built(s) && s.terrain_tiles.pending() == 0
    });
    assert!(
        frame.says("no staged terrain past the store's edge"),
        "{}",
        frame.joined()
    );
    let line = terrain_tiles::line(&alone).expect("a store");
    assert!(!line.contains("fetched"), "row h: nothing fetched: {line}");
    assert_eq!(served.load(Ordering::SeqCst), 0, "row h: no request made");
    let field_alone = bits(&alone);

    // With the mirror as the fill source.
    let template = format!("http://127.0.0.1:{port}/{{ns}}{{lat}}{{ew}}{{lon}}.tif");
    let mut filled = desktop(&dir.join("filled"), &store, &digest, Some(template));
    let frame = until(&mut filled, &mut picture, "the fill drawn", |s| {
        sight_built(s) && !s.viewport.terrain_tiles.fill_drawn().is_empty()
    });
    // Row j: outlined, said, counted apart.
    assert!(!filled.viewport.terrain_tiles.fill_outlines().is_empty());
    assert!(
        frame.says("fetched tile") && frame.says("drawn outlined, outside line of sight"),
        "{}",
        frame.joined()
    );
    assert!(
        !frame.says("no staged terrain past the store's edge"),
        "§8.2: the sentence for missing ground does not show over fetched ground"
    );
    let line = terrain_tiles::line(&filled).expect("a store");
    assert!(
        line.contains("from 1 one-degree tile (n51e010), outside line of sight"),
        "{line}"
    );
    assert_eq!(filled.terrain_tiles.fill_tiles(), ["n51e010"]);
    assert!(served.load(Ordering::SeqCst) >= 1);
    // Fetched into the data directory, with what was fetched recorded.
    let cache = dir.join("filled/data/terrain-fill");
    let record = std::fs::read_to_string(cache.join("n51e010.fetched.json")).expect("recorded");
    assert!(
        record.contains(&format!("http://127.0.0.1:{port}/n51e010.tif")),
        "{record}"
    );
    // Row k: line of sight is the pinned store's alone, bit for bit.
    assert_eq!(
        bits(&filled),
        field_alone,
        "row k: the fill entered line of sight"
    );
    // Row i: every pinned file still matches its manifest, and the manifest the baseline.
    let reopened =
        TerrainStore::open(&store, &digest).expect("row i: the manifest is the pinned one");
    for tile in reopened.index().tiles() {
        reopened
            .read_tile(tile.key())
            .expect("row i: every pinned tile matches");
    }
    let files = walk(&store);
    assert_eq!(
        files.len(),
        reopened.index().len() + 1,
        "row i: nothing was added to the pinned store: {files:?}"
    );
    let _ = std::fs::remove_dir_all(dir);
}

/// Row h: a fill source that cannot be reached fetches nothing, the map and PN-09 say why,
/// and line of sight is the pinned store's. A tile fetched in an earlier session is
/// reopened from the cache with no request.
#[test]
fn an_unreachable_fill_source_is_said_and_a_cached_tile_is_reused() {
    let dir = scratch("unreachable");
    let (store, digest) = pinned(&dir);
    // A port nothing listens on: bound, then let go.
    let closed = {
        let listener = std::net::TcpListener::bind("127.0.0.1:0").expect("a port");
        listener.local_addr().expect("bound").port()
    };
    let template = format!("http://127.0.0.1:{closed}/{{ns}}{{lat}}{{ew}}{{lon}}.tif");
    let mut picture = PictureCache::default();
    let mut state = desktop(&dir.join("one"), &store, &digest, Some(template.clone()));
    let frame = until(&mut state, &mut picture, "the fetch refused", |s| {
        sight_built(s) && s.terrain_tiles.fill_status().contains("not fetched")
    });
    assert!(frame.says("fill n51e010 not fetched"), "{}", frame.joined());
    assert!(frame.says("no staged terrain past the store's edge"));
    let line = terrain_tiles::line(&state).expect("a store");
    assert!(
        line.contains("fetched 0 placed from 0 one-degree tiles"),
        "{line}"
    );
    assert!(line.contains("fill n51e010 not fetched"), "{line}");

    // An earlier session fetched it from a mirror into this data directory.
    let (port, served) = mirror();
    let mirror_source = format!("http://127.0.0.1:{port}/{{ns}}{{lat}}{{ew}}{{lon}}.tif");
    let mut first = desktop(&dir.join("two"), &store, &digest, Some(mirror_source));
    until(&mut first, &mut picture, "the first fetch", |s| {
        !s.terrain_tiles.fill_tiles().is_empty()
    });
    let fetched = served.load(Ordering::SeqCst);
    drop(first);
    // This session's source is unreachable, and the cached tile is reopened.
    let mut again = desktop(&dir.join("two"), &store, &digest, Some(template));
    until(&mut again, &mut picture, "the cached fill drawn", |s| {
        !s.viewport.terrain_tiles.fill_drawn().is_empty()
    });
    assert_eq!(
        served.load(Ordering::SeqCst),
        fetched,
        "nothing was fetched again"
    );
    let _ = std::fs::remove_dir_all(dir);
}

/// Every file under `dir`.
fn walk(dir: &Path) -> Vec<PathBuf> {
    let mut files = Vec::new();
    for entry in std::fs::read_dir(dir).expect("a directory").flatten() {
        let path = entry.path();
        if path.is_dir() {
            files.extend(walk(&path));
        } else {
            files.push(path);
        }
    }
    files
}
