//! A staged terrain store on the desktop (GAP-227,
//! `docs/design/DN-36-staged-terrain-and-map-tiles.md` §4.2, the store reader): the
//! baseline pins the manifest's digest, the desktop opens and verifies the store off the
//! render thread, refuses a manifest whose digest differs or whose frame contradicts the
//! baseline's by name, and places each tile through the single DEM's path. §8.1 row a is
//! a draft criterion, not a gate; these tests are its desktop half.
//!
//! Line of sight over the store is DN-36 §5.2's increment. Until then the desktop says so
//! in the terrain line, and line of sight stays flat; drawing the store by view is
//! `tests/terrain_tiles.rs`.

use std::path::PathBuf;
use std::sync::Arc;

use gungnir_app::state::AppState;
use gungnir_app::terrain::{self, StoreDeclaration, TerrainStatus};
use gungnir_app::update;
use gungnir_config::{ConfigBaseline, TerrainConfig};
use gungnir_data::geospatial::{GridCrs, HeightGrid, TerrainMesh};
use gungnir_data::terrain_store::{
    stage, ManifestSource, StageOptions, TerrainStore, TileKey, TileRefusal,
};
use gungnir_data::{LoadRequest, LoadResult};

fn scratch(name: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!("gungnir-app-store-{name}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).expect("scratch directory");
    dir
}

/// Seven columns by five rows of 30 m cells, heights rising to the north-east, in `crs`.
fn source(origin: [f64; 2], crs: GridCrs) -> HeightGrid {
    let mut heights = Vec::new();
    for row in 0..5_u8 {
        for column in 0..7_u8 {
            heights.push(100.0 + f32::from(4 - row) * 3.0 + f32::from(column));
        }
    }
    HeightGrid {
        columns: 7,
        rows: 5,
        origin,
        cell_size: [30.0, 30.0],
        nodata: None,
        crs,
        vertical: None,
        heights,
    }
}

fn options(frame: &str, vertical: Option<&str>) -> StageOptions {
    StageOptions {
        source: ManifestSource {
            url: "synthetic".into(),
            retrieved: "2026-10-30".into(),
            licence: "none: generated by this test".into(),
        },
        staged_by: "gungnir-app tests".into(),
        frame: frame.into(),
        vertical: vertical.map(str::to_string),
        nad83_realisation: None,
        tile_cells: 2,
        apron_cells: 1,
        levels: None,
    }
}

fn desktop(dir: &std::path::Path, store: &std::path::Path, digest: &str, frame: &str) -> AppState {
    let config = ConfigBaseline {
        data_dir: dir.join("data").to_string_lossy().into_owned(),
        origin: Some([0.959_931, 0.209_44, 0.0]),
        terrain: Some(TerrainConfig {
            path: None,
            store: Some(store.to_string_lossy().into_owned()),
            manifest_sha256: Some(digest.to_string()),
            frame: frame.into(),
            vertical: None,
            nad83_realisation: None,
            vertical_sigma_m: None,
        }),
        geoid_grid_dir: Some(dir.join("no-grid-here").to_string_lossy().into_owned()),
        ..ConfigBaseline::default()
    };
    gungnir_config::validate(&config).expect("valid");
    AppState::with_config(config).expect("starts")
}

/// Tick until the loader answers; a deadlock guard, as `tests/terrain.rs`'s `settle`.
fn settle(state: &mut AppState) {
    for _ in 0..6_000 {
        update::tick(state);
        if !matches!(
            state.terrain,
            TerrainStatus::Loading { .. } | TerrainStatus::NotConfigured
        ) {
            return;
        }
        std::thread::sleep(std::time::Duration::from_millis(10));
    }
    panic!("the loader never answered: {:?}", state.terrain);
}

fn local_store(name: &str) -> (PathBuf, PathBuf, String) {
    let dir = scratch(name);
    let store = dir.join("store");
    let (_, digest) = stage(
        &source([1000.0, 2000.0], GridCrs::Unstated),
        &store,
        &options("local-enu", None),
    )
    .expect("staged");
    (dir, store, digest)
}

#[test]
fn a_pinned_store_is_verified_and_says_line_of_sight_is_flat() {
    let (dir, store, digest) = local_store("verified");
    let mut state = desktop(&dir, &store, &digest, "local-enu");
    settle(&mut state);
    match &state.terrain {
        TerrainStatus::StoreVerified { tiles, levels, .. } => {
            assert_eq!((*tiles, *levels), (12 + 4 + 1, 3));
        }
        other => panic!("{other:?}"),
    }
    assert!(state.terrain_store.is_some());
    assert!(!state.terrain.is_masking());
    assert!(state.height_field.is_none(), "line of sight stays flat");
    let line = state.terrain.line();
    assert!(
        line.contains("manifest verified") && line.contains("not built yet"),
        "{line}"
    );
    let _ = std::fs::remove_dir_all(dir);
}

/// §8.1 row a: a manifest whose digest differs from the baseline's is refused by name.
#[test]
fn a_manifest_whose_digest_differs_from_the_baselines_is_refused_by_name() {
    let (dir, store, _) = local_store("digest");
    let mut state = desktop(&dir, &store, &"ab".repeat(32), "local-enu");
    settle(&mut state);
    match &state.terrain {
        TerrainStatus::Failed { reason, .. } => {
            assert!(reason.contains("manifest.json"), "{reason}");
            assert!(reason.contains("is not the pinned manifest"), "{reason}");
        }
        other => panic!("{other:?}"),
    }
    assert!(state.terrain_store.is_none());
    assert!(
        state.alerts.iter().any(|a| a.contains("not opened")),
        "{:?}",
        state.alerts
    );
    let _ = std::fs::remove_dir_all(dir);
}

#[test]
fn a_store_staged_in_another_frame_is_refused_by_name() {
    let dir = scratch("frame");
    let store = dir.join("store");
    let (_, digest) = stage(
        &source(
            [500_000.0, 6_000_000.0],
            GridCrs::Projected { epsg: Some(32633) },
        ),
        &store,
        &options("epsg:32633", Some("ellipsoidal")),
    )
    .expect("staged");
    let mut state = desktop(&dir, &store, &digest, "local-enu");
    settle(&mut state);
    match &state.terrain {
        TerrainStatus::Failed { reason, .. } => {
            assert!(
                reason.contains("local-enu") && reason.contains("EPSG:32633"),
                "{reason}"
            );
        }
        other => panic!("{other:?}"),
    }
    let _ = std::fs::remove_dir_all(dir);
}

/// One tile through the loader thread, as the desktop will request it.
fn load_tile(store: &Arc<TerrainStore>, key: TileKey) -> LoadResult {
    let (requests, results) = gungnir_data::spawn_loader();
    requests
        .send(LoadRequest::TerrainTile(Arc::clone(store), key))
        .expect("the loader is running");
    results
        .recv_timeout(std::time::Duration::from_secs(60))
        .expect("the loader answers")
}

fn tile_mesh(store: &Arc<TerrainStore>, key: TileKey) -> Result<TerrainMesh, String> {
    match load_tile(store, key) {
        LoadResult::TerrainTile(result) => result.map_err(|e| e.to_string()),
        _ => panic!("a tile request answers with a tile"),
    }
}

/// The tile's own cells placed through `place_tile` sit where the same cells of the whole
/// source sit when it is placed as one DEM: the store changes where the ground is read
/// from, never where it lands.
fn a_tile_lands_where_the_single_dem_does(
    name: &str,
    grid: &HeightGrid,
    declaration: &StoreDeclaration,
) {
    let dir = scratch(name);
    let store = dir.join("store");
    let (_, digest) = stage(
        grid,
        &store,
        &options(&declaration.frame, declaration.vertical.as_deref()),
    )
    .expect("staged");
    let store = Arc::new(TerrainStore::open(&store, &digest).expect("opens"));
    let origin = Some([0.945_073_08, 0.261_799_39, 0.0]);
    let geoid = gungnir_app::geoid::GeoidGrids::default();
    let whole = terrain::place_tile(
        TerrainMesh::from_grid(grid).expect("meshed"),
        declaration,
        origin,
        2026.5,
        &geoid,
    )
    .expect("the single DEM places");
    let key = TileKey {
        level: 0,
        column: 1,
        row: 1,
    };
    let tile = terrain::place_tile(
        tile_mesh(&store, key).expect("the tile loads"),
        declaration,
        origin,
        2026.5,
        &geoid,
    )
    .expect("the tile places");
    // Tile (1, 1) holds source rows 2-3 and columns 2-3; with its apron, the tile's grid
    // starts one cell up and left of that, at source row 1, column 1.
    assert_eq!((tile.columns, tile.rows), (4, 4));
    for tile_row in 0..4_u32 {
        for tile_column in 0..4_u32 {
            let (row, column) = (tile_row + 1, tile_column + 1);
            let a = tile.positions[(tile_row * 4 + tile_column) as usize];
            let b = whole.positions[(row * 7 + column) as usize];
            for axis in 0..3 {
                assert!(
                    (a[axis] - b[axis]).abs() < 1e-3,
                    "row {row}, column {column}: {a:?} against {b:?}"
                );
            }
        }
    }
    let _ = std::fs::remove_dir_all(dir);
}

#[test]
fn a_local_frame_tile_lands_where_the_single_dem_does() {
    a_tile_lands_where_the_single_dem_does(
        "place-local",
        &source([1000.0, 2000.0], GridCrs::Unstated),
        &StoreDeclaration {
            frame: "local-enu".into(),
            vertical: None,
            nad83_realisation: None,
        },
    );
}

