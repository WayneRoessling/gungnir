/// §8.1 row a: a tile whose digest differs from its manifest entry is refused by name, and
/// the rest of the store loads.
#[test]
fn a_tampered_tile_is_refused_by_key_and_the_rest_loads() {
    let (dir, store_dir, digest) = local_store("tampered");
    let store = Arc::new(TerrainStore::open(&store_dir, &digest).expect("opens"));
    let tampered = TileKey {
        level: 1,
        column: 1,
        row: 0,
    };
    let path = store_dir.join(tampered.relative_path());
    let mut bytes = std::fs::read(&path).expect("tile");
    bytes[0] ^= 0xff;
    std::fs::write(&path, bytes).expect("tampered");
    match load_tile(&store, tampered) {
        LoadResult::TerrainTile(Err(err)) => {
            assert_eq!(err.key, tampered);
            assert!(matches!(err.reason, TileRefusal::Digest { .. }), "{err}");
            assert!(err.to_string().contains("tile 1/1_0 refused"), "{err}");
        }
        _ => panic!("the tampered tile was not refused"),
    }
    for entry in store.index().tiles().filter(|t| t.key() != tampered) {
        tile_mesh(&store, entry.key()).expect("the rest of the store loads");
    }
    let _ = std::fs::remove_dir_all(dir);
}
