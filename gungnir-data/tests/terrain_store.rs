//! The staged terrain store (GAP-227, `docs/design/DN-36-staged-terrain-and-map-tiles.md`
//! §4): a store staged from a grid reads back verified, a level-1 cell is the mean of the
//! level-0 cells under it (§8.1 row b, a draft and not a gate), and a manifest or a tile
//! whose digest differs is refused by name while the rest of the store loads (row a's
//! `gungnir-data` half).

// Heights here are small whole numbers and their means, exact in `f32`; a margin would
// hide an averaging that is off by one cell.
#![allow(clippy::float_cmp)]

use std::path::{Path, PathBuf};

use gungnir_data::geospatial::{geotiff, GridCrs, HeightGrid};
use gungnir_data::terrain_store::{
    stage, ManifestSource, StageOptions, StoreError, TerrainStore, TileKey, TileRefusal,
};

/// A fresh, empty directory for one test.
fn scratch(name: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!("gungnir-store-{name}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).expect("scratch directory");
    dir
}

/// Seven columns by five rows of 10 m cells in UTM 33N, heights `10 * row + column`, one
/// no-data cell at row 1, column 1.
fn source() -> HeightGrid {
    let mut heights = Vec::new();
    for row in 0..5_u8 {
        for column in 0..7_u8 {
            heights.push(f32::from(10 * row + column));
        }
    }
    heights[7 + 1] = -9999.0;
    HeightGrid {
        columns: 7,
        rows: 5,
        origin: [500_000.0, 6_000_000.0],
        cell_size: [10.0, 10.0],
        nodata: Some(-9999.0),
        crs: GridCrs::Projected { epsg: Some(32633) },
        vertical: Some(3855),
        heights,
    }
}

fn options() -> StageOptions {
    StageOptions {
        source: ManifestSource {
            url: "synthetic".into(),
            retrieved: "2026-10-30".into(),
            licence: "none: generated by this test".into(),
        },
        staged_by: "gungnir-data tests".into(),
        frame: "epsg:32633".into(),
        vertical: None,
        nad83_realisation: None,
        tile_cells: 2,
        apron_cells: 1,
        levels: None,
    }
}

fn staged(name: &str) -> (PathBuf, String) {
    let dir = scratch(name);
    let (_, digest) = stage(&source(), &dir, &options()).expect("staged");
    (dir, digest)
}

const fn key(level: u8, column: u32, row: u32) -> TileKey {
    TileKey { level, column, row }
}

/// The height at `(row, column)` of a tile's own cells, the apron stepped over.
fn own(grid: &HeightGrid, row: u32, column: u32) -> Option<f32> {
    grid.height_at(row + 1, column + 1)
}

#[test]
fn a_written_geotiff_reads_back_unchanged() {
    let grid = source();
    let mut bytes = std::io::Cursor::new(Vec::new());
    geotiff::write(&mut bytes, &grid).expect("written");
    let back = geotiff::parse(&bytes.into_inner()).expect("parsed");
    assert_eq!(back, grid);
}

#[test]
fn a_staged_store_reads_back_verified() {
    let (dir, digest) = staged("reads");
    let store = TerrainStore::open(&dir, &digest.to_ascii_uppercase()).expect("opens");
    let index = store.index();
    // 7 by 5 in 2-cell tiles: level 0 is 4 by 3 tiles, level 1 (4 by 3 cells) 2 by 2,
    // level 2 (2 by 2 cells) one tile, so three levels.
    assert_eq!(index.levels(), 3);
    assert_eq!(index.len(), 12 + 4 + 1);
    assert_eq!(index.height_range_m(), [0.0, 46.0]);
    for tile in index.tiles() {
        let grid = store.read_tile(tile.key()).expect("every tile reads");
        assert_eq!(
            (grid.columns, grid.rows),
            (tile.columns + 2, tile.rows + 2),
            "{} has its apron",
            tile.key()
        );
        assert_eq!(grid.crs, GridCrs::Projected { epsg: Some(32633) });
        assert_eq!(grid.vertical, Some(3855));
    }
    // Level 0, tile (1, 0): columns 2-3, rows 0-1 of the source; its apron reaches the
    // neighbours' cells, and the north apron row lies past the extent.
    let tile = store.read_tile(key(0, 1, 0)).expect("reads");
    assert_eq!(own(&tile, 0, 0), Some(2.0));
    assert_eq!(own(&tile, 1, 1), Some(13.0));
    assert_eq!(tile.height_at(1, 0), Some(1.0), "west apron is column 1");
    assert_eq!(tile.height_at(0, 1), None, "north apron is past the extent");
    let _ = std::fs::remove_dir_all(dir);
}

/// §8.1 row b: a level-1 cell is the mean of the level-0 cells under it, no-data left out;
/// a level-2 cell the mean of all sixteen, not of four means.
#[test]
fn levels_average_the_cells_under_them() {
    let (dir, digest) = staged("average");
    let store = TerrainStore::open(&dir, &digest).expect("opens");
    let level1 = store.read_tile(key(1, 0, 0)).expect("reads");
    // Source rows 0-1, columns 0-1: 0, 1, 10 and the no-data cell.
    assert_eq!(own(&level1, 0, 0), Some((0.0 + 1.0 + 10.0) / 3.0));
    // Rows 0-1, columns 2-3: 2, 3, 12, 13.
    assert_eq!(own(&level1, 0, 1), Some(7.5));
    let level2 = store.read_tile(key(2, 0, 0)).expect("reads");
    // Rows 0-3, columns 0-3: sixteen cells less the no-data one.
    let mut sum = 0.0_f32;
    for row in 0..4_u8 {
        for column in 0..4_u8 {
            if (row, column) != (1, 1) {
                sum += f32::from(10 * row + column);
            }
        }
    }
    assert_eq!(own(&level2, 0, 0), Some(sum / 15.0));
    // The last level-1 column averages one source column: rows 0-1 of column 6.
    let edge = store.read_tile(key(1, 1, 0)).expect("reads");
    assert_eq!(own(&edge, 0, 1), Some(11.0), "the mean of 6 and 16");
    let _ = std::fs::remove_dir_all(dir);
}

#[test]
fn a_manifest_whose_digest_differs_is_refused_by_name() {
    let (dir, _) = staged("manifest");
    let wrong = "0".repeat(64);
    match TerrainStore::open(&dir, &wrong) {
        Err(StoreError::Digest { path, expected, .. }) => {
            assert!(path.ends_with("manifest.json"), "{}", path.display());
            assert_eq!(expected, wrong);
        }
        other => panic!("expected a digest refusal, got {other:?}"),
    }
    let err = TerrainStore::open(&dir.join("absent"), &wrong).expect_err("no store");
    assert!(matches!(err, StoreError::Missing { .. }), "{err}");
    let _ = std::fs::remove_dir_all(dir);
}

#[test]
fn a_tile_whose_digest_differs_is_refused_and_the_rest_loads() {
    let (dir, digest) = staged("tile");
    let store = TerrainStore::open(&dir, &digest).expect("opens");
    let tampered = key(0, 1, 0);
    let path = dir.join(tampered.relative_path());
    let mut bytes = std::fs::read(&path).expect("tile");
    let last = bytes.len() - 1;
    bytes[last] ^= 1;
    std::fs::write(&path, bytes).expect("tampered");

    let err = store.read_tile(tampered).expect_err("tampered");
    assert_eq!(err.key, tampered);
    assert!(matches!(err.reason, TileRefusal::Digest { .. }), "{err}");
    assert!(
        err.to_string().starts_with("tile 0/1_0 refused: digest"),
        "{err}"
    );
    for tile in store.index().tiles().filter(|t| t.key() != tampered) {
        store
            .read_tile(tile.key())
            .expect("the rest of the store loads");
    }

    std::fs::remove_file(dir.join(key(0, 0, 0).relative_path())).expect("removed");
    let err = store.read_tile(key(0, 0, 0)).expect_err("removed");
    assert!(matches!(err.reason, TileRefusal::Missing(_)), "{err}");
    let err = store.read_tile(key(0, 9, 9)).expect_err("never staged");
    assert_eq!(err.reason, TileRefusal::NotInManifest);
    let _ = std::fs::remove_dir_all(dir);
}

#[test]
fn staging_never_writes_into_an_existing_store() {
    let (dir, digest) = staged("again");
    let err = stage(&source(), &dir, &options()).expect_err("a store is there");
    assert!(err.to_string().contains("already exists"), "{err}");
    TerrainStore::open(&dir, &digest).expect("the first store is untouched");
    let _ = std::fs::remove_dir_all(dir);
}

/// A tile with no height of its own is not written, and the manifest does not list it.
#[test]
fn an_empty_tile_is_not_staged() {
    let mut grid = source();
    for row in 0..2 {
        for column in 4..6 {
            grid.heights[row * 7 + column] = -9999.0;
        }
    }
    let dir = scratch("empty");
    let (manifest, _) = stage(&grid, &dir, &options()).expect("staged");
    assert!(!manifest.tiles.iter().any(|t| t.key() == key(0, 2, 0)));
    assert!(!Path::new(&dir.join(key(0, 2, 0).relative_path())).exists());
    let _ = std::fs::remove_dir_all(dir);
}

/// `terrain stage` (D-162) from a file on this machine: the committed UTM fixture, checked
/// against the digest `testdata/dem/SOURCE.md` publishes for it, staged, and the store it
/// writes opens under the digest it prints.
#[test]
fn terrain_stage_stages_a_checked_source_and_prints_the_digest_to_pin() {
    use gungnir_data::terrain_store::cli;
    let source = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../testdata/dem/small.tif");
    let out = scratch("cli").join("store");
    let args = |sha: &str| -> Vec<String> {
        [
            "stage",
            "--source",
            &source.to_string_lossy(),
            "--out",
            &out.to_string_lossy(),
            "--frame",
            "epsg:32633",
            "--vertical",
            "ellipsoidal",
            "--licence",
            "none: generated for the DEM loader tests",
            "--retrieved",
            "2026-09-06",
            "--source-sha256",
            sha,
            "--tile-cells",
            "2",
        ]
        .iter()
        .map(|s| (*s).to_string())
        .collect()
    };
    let wrong = cli::run("gungnir-node", &args(&"0".repeat(64))).expect_err("a wrong digest");
    assert!(wrong.contains("is not the published source"), "{wrong}");
    assert!(
        !out.exists(),
        "nothing written for a source that did not check"
    );
    let said = cli::run(
        "gungnir-node",
        &args("f506703b66389040ad084f640d5b7736f976a49cb7837b91c172eb91d2fcb4e7"),
    )
    .expect("staged");
    let digest = said
        .lines()
        .find_map(|l| l.strip_prefix("manifest SHA-256 "))
        .expect("the digest is printed");
    let store = TerrainStore::open(&out, digest).expect("the printed digest pins the store");
    let manifest = store.index().manifest();
    assert_eq!(
        manifest.staged_by,
        format!("gungnir-node terrain stage {}", env!("CARGO_PKG_VERSION"))
    );
    assert!(manifest.source.url.starts_with("file:"));
    assert_eq!(manifest.frame, "epsg:32633");
    // Five by four cells in 2-cell tiles: three by two at level 0, the no-data cell's
    // tile still holding three heights.
    assert_eq!(store.index().level_tiles(0), Some([3, 2]));
    for tile in store.index().tiles() {
        store
            .read_tile(tile.key())
            .expect("every staged tile reads");
    }
    let again = cli::run(
        "gungnir-node",
        &args("f506703b66389040ad084f640d5b7736f976a49cb7837b91c172eb91d2fcb4e7"),
    )
    .expect_err("the store is there");
    assert!(again.contains("already exists"), "{again}");
    let local = cli::run(
        "gungnir-app",
        &[
            "stage",
            "--source",
            &source.to_string_lossy(),
            "--out",
            &out.with_file_name("other").to_string_lossy(),
            "--frame",
            "local-enu",
            "--licence",
            "x",
            "--retrieved",
            "y",
        ]
        .iter()
        .map(|s| (*s).to_string())
        .collect::<Vec<_>>(),
    )
    .expect_err("the file states UTM");
    assert!(local.contains("EPSG:32633"), "{local}");
    let _ = std::fs::remove_dir_all(out.parent().expect("scratch"));
}
