//! The node reads the pinned terrain store for its line of sight (GAP-227,
//! `docs/design/DN-36-staged-terrain-and-map-tiles.md` §9): verified against the baseline's
//! digest, its field built over the coverage extent from the store alone, and what it reads,
//! or why it reads nothing, said on the line the node's health log carries.

#![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]

use std::path::PathBuf;

use gungnir_config::{ConfigBaseline, SensorConfig, TerrainConfig};
use gungnir_data::geospatial::{GridCrs, HeightGrid};
use gungnir_data::terrain_store::{stage, ManifestSource, StageOptions, TileKey};
use gungnir_node::terrain::{NodeTerrain, Sight, TerrainStatus};

/// The local frame's origin, 54.148 104 104 N 15 E, as `gungnir-app/tests/terrain_tiles.rs`
/// has it: a UTM zone 33N store's south-west corner lands on it.
const ORIGIN: [f64; 3] = [
    54.148_104_104 * std::f64::consts::PI / 180.0,
    15.0 * std::f64::consts::PI / 180.0,
    0.0,
];

/// The frame the test store is staged in.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Frame {
    /// The deployment's own local frame: 10 m cells from the origin.
    Local,
    /// WGS84 geographic degrees with ellipsoidal heights, its south-west corner on the
    /// origin: placed by any build, since it needs no PROJ.
    Geographic,
    /// UTM zone 33N, ellipsoidal heights, its south-west corner at 500 000 E, 6 000 000 N.
    Utm,
}

/// A 64 by 64 store with 16-cell tiles in `frame`, heights rising east, and a baseline
/// pinning it with one radar at the origin reaching 200 m when `radar`.
fn baseline(name: &str, frame: Frame, radar: bool) -> (ConfigBaseline, PathBuf) {
    let dir = std::env::temp_dir().join(format!(
        "gungnir-node-terrain-{name}-{}",
        std::process::id()
    ));
    let _ = std::fs::remove_dir_all(&dir);
    let mut heights = Vec::new();
    for r in 0..64_u8 {
        for c in 0..64_u8 {
            heights.push(200.0 + f32::from(c) - f32::from(r) * 0.5);
        }
    }
    let (origin, cell_size, crs, declared, vertical) = match frame {
        Frame::Local => (
            [0.0, 0.0],
            [10.0, 10.0],
            GridCrs::Unstated,
            "local-enu",
            None,
        ),
        // 0.000 15 degrees of longitude is about 9.8 m at this latitude, and of latitude
        // about 16.7 m.
        Frame::Geographic => (
            [15.0, 54.148_104_104],
            [0.000_15, 0.000_15],
            GridCrs::Geographic { epsg: Some(4326) },
            "epsg:4326",
            Some("ellipsoidal"),
        ),
        Frame::Utm => (
            [500_000.0, 6_000_000.0],
            [10.0, 10.0],
            GridCrs::Projected { epsg: Some(32633) },
            "epsg:32633",
            Some("ellipsoidal"),
        ),
    };
    let grid = HeightGrid {
        columns: 64,
        rows: 64,
        origin,
        cell_size,
        nodata: None,
        crs,
        vertical: None,
        heights,
    };
    let store = dir.join("store");
    let (_, digest) = stage(
        &grid,
        &store,
        &StageOptions {
            source: ManifestSource {
                url: "synthetic".into(),
                retrieved: "2026-10-31".into(),
                licence: "none: generated by this test".into(),
            },
            staged_by: "gungnir-node tests".into(),
            frame: declared.into(),
            vertical: vertical.map(str::to_string),
            nad83_realisation: None,
            tile_cells: 16,
            apron_cells: 1,
            levels: None,
        },
    )
    .expect("staged");
    let config = ConfigBaseline {
        data_dir: dir.join("data").to_string_lossy().into_owned(),
        origin: Some(ORIGIN),
        terrain: Some(TerrainConfig {
            path: None,
            store: Some(store.to_string_lossy().into_owned()),
            manifest_sha256: Some(digest),
            fill_source: None,
            frame: declared.into(),
            vertical: None,
            nad83_realisation: None,
            vertical_sigma_m: None,
        }),
        geoid_grid_dir: Some(dir.join("no-grid-here").to_string_lossy().into_owned()),
        sensors: if radar {
            vec![radar_at_origin(200.0)]
        } else {
            Vec::new()
        },
        ..ConfigBaseline::default()
    };
    gungnir_config::validate(&config).expect("valid");
    (config, dir)
}

fn radar_at_origin(range_m: f64) -> SensorConfig {
    SensorConfig {
        id: 1,
        modality: "radar".into(),
        position: [ORIGIN[0], ORIGIN[1], 10.0],
        max_range_m: range_m,
        control_endpoint: None,
        maintenance: Vec::new(),
        detection_model: None,
        azimuth_sector: None,
        elevation_band: None,
    }
}

/// Poll as the node's tick does until line of sight is no longer building; a deadlock guard.
fn settle(terrain: &mut NodeTerrain, config: &ConfigBaseline) {
    for _ in 0..3_000 {
        terrain.poll(config);
        if !matches!(
            terrain.status(),
            TerrainStatus::StoreVerified {
                sight: Sight::Building,
                ..
            }
        ) {
            return;
        }
        std::thread::sleep(std::time::Duration::from_millis(10));
    }
    panic!("line of sight never settled: {}", terrain.line());
}

/// DN-36 §9 and §5.2: a local-frame store pinned by the baseline is verified, and line of
/// sight reads it over the 800 m extent about the radar, ground inside the store and no
/// data, so flat, past its edge, said on the health line.
#[test]
fn the_node_builds_line_of_sight_from_a_local_frame_store() {
    let (config, dir) = baseline("local", Frame::Local, true);
    let mut terrain = NodeTerrain::start(&config);
    assert!(terrain.field().is_none(), "nothing is read before the tick");
    settle(&mut terrain, &config);
    let field = terrain.field().expect("a field");
    assert!(
        (field.cell_m - 10.0).abs() < 1e-6,
        "level 0's cells: {}",
        field.cell_m
    );
    assert!(field.origin_enu[0] < -399.0 && field.origin_enu[1] < -399.0);
    // Inside the store, the staged height: column 10, row 24 from the north, 200 + 10 - 12.
    // South-west of it, inside the extent, no data.
    let up = field.up_at(105.0, 395.0).expect("ground inside the store");
    assert!((up - 198.0).abs() < 1e-3, "{up}");
    assert!(field.up_at(-200.0, -200.0).is_none());
    assert!(matches!(
        terrain.status(),
        TerrainStatus::StoreVerified {
            tiles: 21,
            sight: Sight::Built {
                level: 0,
                refused: 0,
                past_edge: true,
                ..
            },
            ..
        }
    ));
    let line = terrain.line();
    assert!(
        line.contains("manifest verified")
            && line.contains("reads the pinned store at level 0 over the coverage extent")
            && line.contains("past the store's edge"),
        "{line}"
    );
    // The extent did not move: polling again keeps the same field rather than painting anew.
    let before = terrain.field().map(std::ptr::from_ref);
    terrain.poll(&config);
    assert_eq!(terrain.field().map(std::ptr::from_ref), before);
    let _ = std::fs::remove_dir_all(dir);
}

/// The extent moves when the baseline's sensors do, and the field is built again over the
/// new one (DN-36 §5.2): the node's tick asks for it, as the desktop's does.
#[test]
fn the_field_follows_the_coverage_extent() {
    let (mut config, dir) = baseline("extent", Frame::Local, true);
    let mut terrain = NodeTerrain::start(&config);
    settle(&mut terrain, &config);
    let first = terrain.field().expect("a field").clone();
    config.sensors = vec![radar_at_origin(300.0)];
    terrain.poll(&config);
    settle(&mut terrain, &config);
    let second = terrain.field().expect("a field again");
    assert!(second.origin_enu[0] < first.origin_enu[0] - 199.0);
    // With nothing declared to cover, there is no extent and no field, and the line says why.
    config.sensors.clear();
    terrain.poll(&config);
    assert!(terrain.field().is_none());
    let line = terrain.line();
    assert!(
        line.contains("not built: no sensor") && line.contains("flat (optimistic)"),
        "{line}"
    );
    let _ = std::fs::remove_dir_all(dir);
}

/// A manifest whose digest differs from the baseline's is refused by name, and nothing is
/// read: line of sight stays flat and the line says so (DN-36 §8.1 row a, a draft).
#[test]
fn a_store_whose_manifest_differs_is_refused_by_name() {
    let (mut config, dir) = baseline("refused", Frame::Local, true);
    if let Some(terrain) = config.terrain.as_mut() {
        terrain.manifest_sha256 = Some("0".repeat(64));
    }
    let mut terrain = NodeTerrain::start(&config);
    terrain.poll(&config);
    assert!(matches!(terrain.status(), TerrainStatus::Refused { .. }));
    assert!(terrain.field().is_none());
    let line = terrain.line();
    assert!(
        line.contains("not opened") && line.contains("flat (optimistic)"),
        "{line}"
    );
    let _ = std::fs::remove_dir_all(dir);
}

/// A tile refused by its digest is flat where it lies and counted, and the rest of the
/// store is read (DN-36 §5.3).
#[test]
fn a_refused_tile_is_flat_and_counted() {
    let (config, dir) = baseline("tile", Frame::Local, true);
    let key = TileKey {
        level: 0,
        column: 0,
        row: 3,
    };
    let store = dir.join("store");
    let path = store.join(key.relative_path());
    let mut bytes = std::fs::read(&path).expect("tile");
    bytes[0] ^= 0xff;
    std::fs::write(&path, bytes).expect("tampered");
    let mut terrain = NodeTerrain::start(&config);
    settle(&mut terrain, &config);
    // Tile 0/0_3 is the south-west 160 m square; its neighbour to the east still reads.
    let field = terrain.field().expect("a field");
    assert!(field.up_at(80.0, 80.0).is_none());
    assert!(field.up_at(240.0, 80.0).is_some());
    let line = terrain.line();
    assert!(line.contains("1 refused and flat"), "{line}");
    let _ = std::fs::remove_dir_all(dir);
}

/// What the node reads nothing from is said too: no terrain, and one DEM, which only the
/// desktop reads.
#[test]
fn the_node_says_why_it_reads_no_terrain() {
    let none = NodeTerrain::start(&ConfigBaseline::default());
    assert_eq!(none.status(), &TerrainStatus::NotConfigured);
    assert!(none.line().contains("no terrain configured"));

    let one = ConfigBaseline {
        terrain: Some(TerrainConfig {
            path: Some("dem.tif".into()),
            store: None,
            manifest_sha256: None,
            fill_source: None,
            frame: "local-enu".into(),
            vertical: None,
            nad83_realisation: None,
            vertical_sigma_m: None,
        }),
        ..ConfigBaseline::default()
    };
    let mut one = NodeTerrain::start(&one);
    one.poll(&ConfigBaseline::default());
    assert!(one.field().is_none());
    let line = one.line();
    assert!(
        line.contains("only the desktop reads") && line.contains("flat (optimistic)"),
        "{line}"
    );
}

/// D-164: a fill source the baseline names is never read by the node's line of sight, and
/// the line says so beside what it does read.
#[test]
fn a_fill_source_is_never_read_here() {
    let (mut config, dir) = baseline("fill", Frame::Local, true);
    if let Some(terrain) = config.terrain.as_mut() {
        terrain.fill_source = Some("https://example.invalid/{ns}{lat}{ew}{lon}.tif".into());
    }
    let mut terrain = NodeTerrain::start(&config);
    settle(&mut terrain, &config);
    assert!(terrain.field().is_some());
    let line = terrain.line();
    assert!(line.contains("never read here (D-164)"), "{line}");
    let _ = std::fs::remove_dir_all(dir);
}

/// A store in WGS84 geographic degrees with ellipsoidal heights is a real-world CRS that
/// needs no PROJ, so any build places it: its south-west corner lands on the origin, and
/// line of sight reads it there, its up the staged height less the earth's curvature.
#[test]
fn a_geographic_store_is_placed_without_proj() {
    let (config, dir) = baseline("geographic", Frame::Geographic, true);
    let mut terrain = NodeTerrain::start(&config);
    settle(&mut terrain, &config);
    let field = terrain
        .field()
        .unwrap_or_else(|| panic!("{}", terrain.line()));
    // 30 m east and 50 m north of the corner is 2.57 cells east of the first cell's centre
    // and 60.5 rows south of the north row's: 200 + 2.57 - 30.25 m, to the curvature's
    // fraction of a millimetre and the cells' size worked out at this latitude.
    let up = field.up_at(30.0, 50.0).expect("ground near the origin");
    assert!((up - 172.3).abs() < 0.5, "{up}");
    assert!(
        field.up_at(-150.0, -150.0).is_none(),
        "south-west of the store"
    );
    let _ = std::fs::remove_dir_all(dir);
}

/// The same through PROJ: a UTM store's tiles placed into local ENU, its south-west corner
/// on the origin.
#[cfg(feature = "crs")]
#[test]
fn a_utm_store_is_placed_through_proj() {
    let (config, dir) = baseline("utm", Frame::Utm, true);
    let mut terrain = NodeTerrain::start(&config);
    settle(&mut terrain, &config);
    let field = terrain
        .field()
        .unwrap_or_else(|| panic!("{}", terrain.line()));
    // Column 10, row 53 from the north: 200 + 10 - 26.5 m, to the zone's scale factor.
    let up = field.up_at(105.0, 105.0).expect("ground inside the store");
    assert!((up - 183.5).abs() < 1.0, "{up}");
    assert!(
        field.up_at(-150.0, -150.0).is_none(),
        "south-west of the store"
    );
    let _ = std::fs::remove_dir_all(dir);
}

/// Without the `crs` feature, a store in a projected frame is refused by name, and line of
/// sight stays flat rather than reading ground placed somewhere it is not.
#[cfg(not(feature = "crs"))]
#[test]
fn a_utm_store_is_refused_by_name_without_crs() {
    let (config, dir) = baseline("utm-refused", Frame::Utm, true);
    let mut terrain = NodeTerrain::start(&config);
    settle(&mut terrain, &config);
    assert!(terrain.field().is_none());
    let line = terrain.line();
    assert!(
        line.contains("needs the crs feature") && line.contains("flat (optimistic)"),
        "{line}"
    );
    let _ = std::fs::remove_dir_all(dir);
}
